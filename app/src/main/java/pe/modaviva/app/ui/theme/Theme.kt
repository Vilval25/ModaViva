/**
 * Tema de ModaViva. No usa dynamic color: la app muestra siempre su propia
 * paleta en lugar de los colores del fondo de pantalla.
 *
 * Elige el esquema según el modo oscuro y, desde Android 14, según el nivel
 * de contraste que el usuario configuró en Accesibilidad.
 */
@Composable
fun ModaVivaTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val contrast = systemContrast(LocalContext.current)
    val colorScheme = colorSchemeFor(darkTheme, contrast)

    MaterialTheme(
        colorScheme = colorScheme,
        typography = AppTypography,
        shapes = AppShapes,
        content = content,
    )
}

private enum class Contrast { STANDARD, MEDIUM, HIGH }

private fun systemContrast(context: Context): Contrast {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.UPSIDE_DOWN_CAKE) return Contrast.STANDARD
    val level = context.getSystemService(UiModeManager::class.java)?.contrast ?: 0f
    // UiModeManager.getContrast() devuelve un valor en [-1, 1]; los cortes
    // siguen la referencia de Material Theme Builder.
    return when {
        level >= 2f / 3 -> Contrast.HIGH
        level >= 1f / 3 -> Contrast.MEDIUM
        else -> Contrast.STANDARD
    }
}

private fun colorSchemeFor(darkTheme: Boolean, contrast: Contrast): ColorScheme =
    when (contrast) {
        Contrast.STANDARD -> if (darkTheme) darkScheme else lightScheme
        Contrast.MEDIUM ->
            if (darkTheme) mediumContrastDarkColorScheme else mediumContrastLightColorScheme
        Contrast.HIGH ->
            if (darkTheme) highContrastDarkColorScheme else highContrastLightColorScheme
    }
